export function LegalPage({ page }) {
  const content = pages[page];

  if (!content) {
    return <main id="main-content" className="account-page"><article className="account-card policy-card"><h1>Page not found</h1><Link href="/">Back to home</Link></article></main>;
  }

  const agreementBlocks = page === 'school'
    ? schoolAgreement.trim().split(/\n\s*\n/)
    : [];

  return (
    <main id="main-content" className="account-page">
      <article className="account-card policy-card">
        <Link href="/">← Back to home</Link>
        {page === 'school' ? (
          <div className="school-agreement-content">
            {agreementBlocks.map((block, index) => {
              const lines = block.split('\n').map(line => line.trim()).filter(Boolean);
              const text = lines.join(' ');
              const heading = text.match(/^(#{1,3})\s+(.+)$/);
              const listItems = lines.filter(line => /^([-*]|\d+\.)\s+/.test(line));
              const tableRows = lines.filter(line => /^\|.*\|$/.test(line));

              if (heading) {
                const Heading = heading[1].length === 1 ? 'h1' : heading[1].length === 2 ? 'h2' : 'h3';
                return <Heading key={index}>{heading[2]}</Heading>;
              }

              if (text === '---') {
                return <hr key={index} />;
              }

              if (tableRows.length) {
                const rows = tableRows
                  .filter(line => !/^\|[\s:-|]+\|$/.test(line))
                  .map(line => line.split('|').slice(1, -1).map(cell => cell.trim()));
                const [header, ...body] = rows;
                return (
                  <div className="school-agreement-table-wrap" key={index}>
                    <table className="school-agreement-table">
                      <thead><tr>{header.map((cell, cellIndex) => <th key={cellIndex}>{cell}</th>)}</tr></thead>
                      <tbody>{body.map((row, rowIndex) => <tr key={rowIndex}>{row.map((cell, cellIndex) => <td key={cellIndex}>{cell}</td>)}</tr>)}</tbody>
                    </table>
                  </div>
                );
              }

              if (listItems.length === lines.length) {
                const List = /^\d+\.\s+/.test(lines[0]) ? 'ol' : 'ul';
                return <List key={index}>{lines.map((line, lineIndex) => <li key={lineIndex}>{line.replace(/^([-*]|\d+\.)\s+/, '')}</li>)}</List>;
              }

              return <p key={index}>{text.replace(/\*\*(.*?)\*\*/g, '$1')}</p>;
            })}
          </div>
        ) : (
          <>
            <div className="form-heading">
              <p className="eyebrow">{content.eyebrow}</p>
              <h1>{page === 'terms' ? 'Terms and Conditions of Use' : content.title}</h1>
              <p>{content.intro}</p>
              {page === 'terms' && <p><strong>I-WIN Learning Solutions Private Limited</strong></p>}
              {page === 'terms' && <p>Website: <a href="https://www.i-winlearning.com">www.i-winlearning.com</a></p>}
            </div>
            {content.sections.map(([title, body]) => (
              <section key={title}>
                <h2>{title}</h2>
                {Array.isArray(body) ? body.map(paragraph => <p key={paragraph}>{paragraph}</p>) : <p>{body}</p>}
              </section>
            ))}
          </>
        )}
        {page === 'terms' && <p className="policy-contact">© 2026 I-WIN Learning Solutions Private Limited. All Rights Reserved.</p>}
        {page !== 'school' && <p className="policy-contact">
          Contact: <a href="mailto:sivaram@i-winlearning.com">sivaram@i-winlearning.com</a>
        </p>}
      </article>
    </main>
  );
}
